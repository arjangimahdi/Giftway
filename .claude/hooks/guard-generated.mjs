// PreToolUse hook: block hand-edits to generated or lock files.
// Exit 2 = block the tool call and show stderr to Claude.
import { readFileSync } from "node:fs";
import { relative, resolve } from "node:path";

const input = JSON.parse(readFileSync(0, "utf8"));
const filePath = input?.tool_input?.file_path;
if (!filePath) process.exit(0);

// Paths below are relative to the Nx workspace, one level under the repo root.
const workspace = `${process.env.CLAUDE_PROJECT_DIR ?? process.cwd()}/giftway-ws`;
const rel = relative(workspace, resolve(workspace, filePath)).replaceAll(
  "\\",
  "/",
);

const blocked = [
  {
    test: /^packages\/tokens\/src\/generated\//,
    why: "generated by style-dictionary — edit packages/tokens/tokens/*.json and run `npx nx run tokens:generate`",
  },
  { test: /(^|\/)dist\//, why: "build output — edit the source instead" },
  { test: /(^|\/)out-tsc\//, why: "build output — edit the source instead" },
  {
    test: /^package-lock\.json$/,
    why: "managed by npm — change package.json and run `npm install`",
  },
  { test: /\.tsbuildinfo$/, why: "TypeScript build cache" },
];

for (const { test, why } of blocked) {
  if (test.test(rel)) {
    console.error(`Blocked: ${rel} is ${why}.`);
    process.exit(2);
  }
}
